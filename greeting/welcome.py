def greeting(speed: float = 1, fast_adjust: float = 1, slow_adjust: float = 1, bloomberg_adjust: float = 1, transition_adjust: float = 1):
    """
    Plays a multi-stage Matrix-style terminal animation.

    Parameters
    ----------
    speed : float
        Base speed controlling overall animation pace.
    fast_adjust : float
        Multiplier for faster text segments.
    slow_adjust : float
        Multiplier for slower text segments.
    bloomberg_adjust : float
        Speed modifier for the Bloomberg animation.
    transition_adjust : float
        Controls pause duration between stages.
    """

    # speed is miliseconds of delay per frame
    fast = speed * 0.1 * fast_adjust
    slow = speed * 1.5 * slow_adjust
    bloomberg = speed * 0.02 * bloomberg_adjust
    transition = 1 * transition_adjust

    txt_animator(path=matrix_text_file_path, char_speed=fast/2, line_speed=slow/2, direction="top_bottom", clear=True)
    time.sleep(transition/2)
    print() # just so hands ascii art doesnt overlap
    txt_animator(matrix_file_path, line_speed=fast*1.5, direction="top_bottom", clear=False)
    time.sleep(transition*2)
    txt_animator(bloomberg_file_path, line_speed=bloomberg, direction="left_right", clear=True)

def default_greeting(speed: float):
    """Calls greeting() with the given speed parameter, which influences various aspects of the animation speed."""
    greeting(speed=speed)
