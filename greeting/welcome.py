import time
import os
from pathlib import Path


BASE_DIR = Path(__file__).parent
matrix_text = ["Wake up, Neo...", "The matrix has you...", "Follow the white rabbit.\n"]
bloomberg_file_path = str(BASE_DIR / "assets" / "bloomberg_art.txt")
matrix_file_path = str(BASE_DIR / "assets" / "matrix_art.txt")
matrix_text_file_path = str(BASE_DIR / "assets" / "matrix_greeting.txt")
FRAMERATE = 60

def clear_terminal():
    match os.name:
        case "nt":
            os.system("cls")
        case "posix":
            os.system("clear")
        case "os2" | "ce":
            os.system("cls")
        case "java" | "riscos":
            # Fallback: ANSI escape sequence
            print("\033[H\033[J")
        case _:
            print("Clear screen not supported for this OS")
    

def txt_to_list(matrix_file_path: str) -> list[str]:
    with open(matrix_file_path, "r", encoding="utf-8") as f:
        lines = f.read().split("\n")
    return lines

def instant_animator(lines: list[str], a, b, c):
    # This isn't very elegant, but abc captures the nonexistent input parameters
    for line in lines:
        print(line)

def top_bottom_animator(lines: list[str], char_speed: float, line_speed: float, direction: str):
    for i, line in enumerate(lines):
        for char in line:
            print(char, end='', flush=True)
            time.sleep(char_speed)
        if i < len(lines)-1: print(); time.sleep(line_speed) # only wait and newline if not last iteration

def left_right_animator(lines: list[str], char_speed: float, column_speed: float, direction: str):
    longest_line: str = len(max(lines, key=len))
    number_of_lines: int = len(lines)

    animation_start: float = 0
    vertical_lines_to_print: str = [""] * number_of_lines
    for x in range(longest_line):
        animation_start = time.time()
        clear_terminal()
        for y in range(number_of_lines):
            vertical_lines_to_print[y] += lines[y][x] if x < len(lines[y]) else ""
            print(vertical_lines_to_print[y])
        
        if x == longest_line: break
        while (time.time() < animation_start + column_speed):
            time.sleep(1/FRAMERATE)

def animator(lines: list[str], char_speed: float = 0, line_speed: float = 0, direction: str = "instant", clear: bool = False):
    if clear:
        clear_terminal()

    animation_executor: function = None
    if direction == "top_bottom":
        animation_executor = top_bottom_animator
    elif direction == "left_right":
        animation_executor = left_right_animator
    elif direction == "instant":
        animation_executor = instant_animator
    else:
        animation_executor = instant_animator

    animation_executor(lines, char_speed, line_speed, direction)


def txt_animator(path: str, char_speed: int = 0, line_speed: int = 0, direction: str = "instant", clear: bool = False):
    animator(txt_to_list(path), char_speed, line_speed, direction, clear)

